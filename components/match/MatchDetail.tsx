/* ---------- Live panel helpers ---------- */
function lastWicketInfo(inn: InningsSim) {
  const f = inn.fow[inn.fow.length - 1];
  if (!f) return null;
  const b = inn.bat.find(x => x.name === f.name)!;
  return `${f.name} ${b.r}(${b.b}) – ${f.score}/${f.wk} in ${f.ov} ov`;
}
function partnership(inn: InningsSim) {
  let r = 0, b = 0;
  for (let i = inn.comm.length - 1; i >= 0 && inn.comm[i].kind !== 'W'; i--) {
    const c = inn.comm[i];
    r += c.kind === 'wd' || c.kind === 'lb' ? 1 : +c.kind;
    if (c.kind !== 'wd') b++;
  }
  return `${r}(${b})`;
}
function last10(inn: InningsSim) {
  const o = inn.overs.slice(-10);
  const r = o.reduce((s, x) => s + x.runs, 0), w = o.reduce((s, x) => s + x.chips.filter(c => c === 'W').length, 0);
  return `${r} runs, ${w} wkt${w === 1 ? '' : 's'}`;
}
function RecentBalls({ inn }: { inn: InningsSim }) {
  const out: ReactNode[] = [];
  inn.overs.slice(-3).forEach((o, i) => { if (i) out.push(<span key={`sep${i}`} className="w-px h-6 bg-slate-300 mx-1" aria-hidden="true"></span>); o.chips.forEach((c, k) => out.push(<Chip key={`${i}-${k}`} v={c} />)); });
  return <>{out}</>;
}

