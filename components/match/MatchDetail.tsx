function BallRow({ c }: { c: Ball }) {
  const hi = ['4', '6', 'W'].includes(c.kind);
  return (
    <div className="flex gap-3 py-3 border-b border-slate-100 last:border-0">
      <div className="w-12 shrink-0 flex flex-col items-center gap-1"><b className="text-sm text-slate-800 tabular-nums">{c.ov}</b>{hi ? <Chip v={c.kind} size="w-6 h-6" /> : null}</div>
      {/* commentary text is generated by lib/cricket.ts and contains <b> markup */}
      <p className="text-sm text-slate-700 leading-relaxed" dangerouslySetInnerHTML={{ __html: `${c.bowler} to ${c.batter}, ${c.text}` }} />
    </div>
  );
}
function commentary(inn: InningsSim, count: number) {
  const byOver: Record<number, Ball[]> = {};
  inn.comm.forEach(c => (byOver[parseInt(c.ov) + 1] = byOver[parseInt(c.ov) + 1] || []).push(c));
  const overs = inn.overs.slice().reverse().slice(0, count);
  return overs.map(o => <Fragment key={o.no}>{o.done ? <OverSummary inn={inn} o={o} /> : null}{(byOver[o.no] || []).slice().reverse().map((c, k) => <BallRow key={k} c={c} />)}</Fragment>);
}
/** shows `initial` overs, then 10 more per "Load more" click */
function CommentaryBlock({ inn, initial, id }: { inn: InningsSim; initial: number; id: string }) {
  const [count, setCount] = useState(initial);
  return (
    <>
      <div id={id}>{commentary(inn, count)}</div>
      {inn.overs.length > count ? <button type="button" data-more={id} data-from={count} onClick={() => setCount(c => c + 10)} className="mt-3 w-full rounded-lg border border-slate-200 min-h-[44px] text-sm font-semibold text-brand-600 hover:bg-brand-50 transition">Load more commentary</button> : null}
    </>
  );
}

/* ---------- Graphs (inline SVG) ---------- */
function Manhattan({ inn }: { inn: InningsSim }) {
  const W = 640, H = 220, P = 28, n = inn.overs.length;
  const max = Math.max(6, ...inn.overs.map(o => o.runs));
  const bw = (W - P * 2) / n;
  const ticks = [0, Math.round(max / 2), max];
  return (
    <svg viewBox={`0 0 ${W} ${H}`} className="w-full h-auto" role="img" aria-label={`Runs per over for ${TEAMS[inn.team].name}`}>
      {ticks.map((t, k) => { const y = H - P - (t / max) * (H - P * 2); return <Fragment key={k}><line x1={P} x2={W - P} y1={y} y2={y} stroke="#E2E8F0" /><text x={P - 6} y={y + 4} fontSize="10" textAnchor="end" fill="#94A3B8">{t}</text></Fragment>; })}
      {inn.overs.map((o, i) => {
        const h = (o.runs / max) * (H - P * 2), x = P + i * bw, y = H - P - h, w = o.chips.includes('W');
        return <Fragment key={i}><rect x={x + bw * .15} y={y} width={Math.max(1, bw * .7)} height={h} rx="1.5" fill={w ? '#E53935' : '#0B7A6F'}><title>{`Over ${o.no}: ${o.runs} runs${w ? ', wicket' : ''}`}</title></rect>
          {w ? <circle cx={x + bw / 2} cy={y - 6} r="3.5" fill="#E53935" /> : null}</Fragment>;
      })}
      <text x={W / 2} y={H - 6} fontSize="10" textAnchor="middle" fill="#94A3B8">Overs</text>
    </svg>
  );
}
function Worm({ inns }: { inns: InningsSim[] }) {
  const W = 640, H = 220, P = 28;
  const maxO = Math.max(...inns.map(i => i.overs.length)), maxR = Math.max(...inns.map(i => i.score));
  const colors = ['#0B7A6F', '#FFB800', '#1A2B6D', '#E53935'];
  const x = (o: number) => P + (o / maxO) * (W - P * 2), y = (r: number) => H - P - (r / maxR) * (H - P * 2);
  return (
    <>
      <svg viewBox={`0 0 ${W} ${H}`} className="w-full h-auto" role="img" aria-label="Worm chart comparing cumulative runs">
        {[0, .5, 1].map(f => <Fragment key={f}><line x1={P} x2={W - P} y1={y(maxR * f)} y2={y(maxR * f)} stroke="#E2E8F0" /><text x={P - 6} y={y(maxR * f) + 4} fontSize="10" textAnchor="end" fill="#94A3B8">{Math.round(maxR * f)}</text></Fragment>)}
        {inns.map((inn, k) => <polyline key={k} fill="none" stroke={colors[k]} strokeWidth="2.5" strokeLinejoin="round" points={`${P},${y(0)} ${inn.overs.map(o => `${x(o.no)},${y(o.score!)}`).join(' ')}`} />)}
      </svg>
      <div className="flex gap-4 justify-center text-xs mt-2">{inns.map((inn, k) => <span key={k} className="flex items-center gap-1.5"><span className="w-3 h-1 rounded" style={{ background: colors[k] }}></span>{teamShort(inn.team)}</span>)}</div>
    </>
  );
}

